# Component files, one generated schema per file, mirroring the one-file-per-operation
# convention. Each stem maps to the single schema it owns and the stem is the file name
# (e.g. normal_parameters -> components/normal_parameters.yaml).
#
# One-schema-per-file is an intentional reversal of the earlier "one cohesive concept
# per file" grouping: profile (ProfileStep + Profile) and the error concept (Error +
# ErrorType) used to share a file. We chose artifact uniformity over concept grouping so
# every component file is single-schema, which also regularizes the name -> file-stem
# mapping a later cross-file $ref refactor depends on. Deliberate invariant change, not drift.
#   - The error concept is likewise split in the Python module layer: error.py (Error) and
#     error_type.py (ErrorType), mirroring the error.yaml and error_type.yaml artifacts.
#   - Profile (the Annotated[list[ProfileStep], max_length=127] alias in profile.py) is
#     intentionally a Python-only convenience alias used in API signatures. It is
#     deliberately NOT exported as a generated schema; only ProfileStep emits.
#
# Root-shape note: each file keeps a top-level {SchemaName: schema} mapping, so a single-
# schema concept still nests under its schema-name key. Collapsing that now redundant
# wrapper key is a deferred refinement, intentionally left out here so the generated
# component root shape stays unchanged by this split.
COMPONENTS: dict[str, dict[str, Any]] = {
    "normal_parameters": {"NormalParameters": NormalParameters},
    "strobe_parameters": {"StrobeParameters": StrobeParameters},
    "trigger_parameters": {"TriggerParameters": TriggerParameters},
    "channel_state": {"ChannelState": ChannelState},
    "device_info": {"DeviceInfo": DeviceInfo},
    "device_descriptor": {"DeviceDescriptor": DeviceDescriptor},
    "controller_capabilities": {"ControllerCapabilities": ControllerCapabilities},
    "operating_mode": {"OperatingMode": OperatingMode},
    "trigger_polarity": {"TriggerPolarity": TriggerPolarity},
    "module_type": {"ModuleType": ModuleType},
    "profile_step": {"ProfileStep": ProfileStep},
    "error": {"Error": Error},
    "error_type": {"ErrorType": ErrorType},
}


def _schema_for(obj: Any) -> dict:
    """Pick the right schema export for a model, union, alias, or enum."""
    if isinstance(obj, type) and hasattr(obj, "model_json_schema"):
        return _model_schema(obj)
    return _adapter_schema(obj)


def generate_components() -> dict[str, str]:
    """Write one file per component concept; return a name -> file index."""
    components_dir = SCHEMAS_DIR / "components"
    index: dict[str, str] = {}
    for concept, members in COMPONENTS.items():
        _dump(
            components_dir / f"{concept}.yaml",
            {name: _schema_for(obj) for name, obj in members.items()},
        )
        index[concept] = f"components/{concept}.yaml"
    return index


def generate_operations() -> dict[str, Any]:
    """Write one self-contained file per operation; return an operation index."""
    operations_dir = SCHEMAS_DIR / "operations"
    index: dict[str, Any] = {}
    for name, (request, reply) in OPERATIONS.items():
        _dump(
            operations_dir / f"{name}.yaml",
            {
                "operation": name,
                "request": _model_schema(request),
                "reply": _adapter_schema(reply),
            },
        )
        index[name] = {
            "request": f"operations/{name}.yaml#/request",
            "reply": f"operations/{name}.yaml#/reply",
        }
    return index


def generate_index(
    operation_index: dict[str, Any], component_index: dict[str, str]
) -> None:
    """Write the top-level operations.yaml index over operations and components."""
    _dump(
        SCHEMAS_DIR / "operations.yaml",
        {"operations": operation_index, "components": component_index},
    )


def main() -> None:
    component_index = generate_components()
    operation_index = generate_operations()
    generate_index(operation_index, component_index)
    print(f"Wrote schema artifacts under {SCHEMAS_DIR}")


if __name__ == "__main__":
    main()
